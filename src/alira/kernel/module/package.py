"""Install a declarative source set that can be retried after interruption."""

import hashlib
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from dataclasses import dataclass
from pathlib import Path
from tempfile import TemporaryDirectory
from urllib.parse import urlsplit

import yaml

from alira.kernel.module.catalog import ModuleCatalog, module_directory
from alira.kernel.module.dependencies.types import (
    DependencyError,
    DependencyResolutionError,
)
from alira.kernel.module.sources import prepare_module_source


@dataclass(frozen=True)
class PackageSource:
    source: str
    ref: str | None = None


class _PackageLoader(yaml.SafeLoader):
    def construct_mapping(self, node, deep=False):
        mapping = super().construct_mapping(node, deep=deep)
        if len(mapping) != len(node.value):
            raise yaml.constructor.ConstructorError(
                None, None, "Duplicate package key", node.start_mark
            )
        return mapping


def read_package(path: Path) -> list[PackageSource]:
    """Resolve local archives relative to the manifest, never the current cwd."""
    path = path.expanduser().resolve()
    try:
        data = yaml.load(path.read_text(encoding="utf-8"), Loader=_PackageLoader)
    except (OSError, UnicodeError, yaml.YAMLError) as exc:
        raise DependencyError(
            "Cannot read package.yml; check the file and YAML syntax"
        ) from exc
    if (
        not isinstance(data, dict)
        or data.keys() != {"modules"}
        or not isinstance(data["modules"], list)
        or not data["modules"]
    ):
        raise DependencyError("package.yml must contain a nonempty modules list")
    sources = []
    for item in data["modules"]:
        if (
            not isinstance(item, dict)
            or not item.keys() <= {"source", "ref"}
            or not isinstance(item.get("source"), str)
            or not item["source"].strip()
            or (
                "ref" in item
                and (not isinstance(item["ref"], str) or not item["ref"].strip())
            )
        ):
            raise DependencyError(
                "Each package module needs source and an optional nonempty ref"
            )
        source = item["source"]
        if not urlsplit(source).scheme:
            source = str((path.parent / Path(source).expanduser()).resolve())
        sources.append(PackageSource(source, item.get("ref")))
    return sources


def _source_tree(directory: Path) -> dict[Path, bytes | None]:
    """Compare content, including empty directories; ignore generated bytecode."""
    entries = {}
    for path in directory.rglob("*"):
        relative = path.relative_to(directory)
        if "__pycache__" in relative.parts:
            continue
        if path.is_symlink():
            raise DependencyError(
                "Existing module contains symbolic links; sources are preserved"
            )
        if path.is_dir():
            entries[relative] = None
        else:
            with path.open("rb") as stream:
                entries[relative] = hashlib.file_digest(stream, "sha256").digest()
    return entries


@asynccontextmanager
async def install_package_sources(
    modules_dir: Path, sources: list[PackageSource]
) -> AsyncIterator[None]:
    """Prepare the complete set before publishing; preserve matching retry inputs.

    Each source rename is atomic. Ordinary publication failures undo new moves;
    SIGKILL may leave a subset published, which the next invocation verifies and
    reuses. No dependency records or interpreter packages are changed here.
    """
    modules_dir.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(prefix=".alira-package-", dir=modules_dir) as temporary:
        staging = Path(temporary)
        prepared = {}
        pending = {}
        for index, source in enumerate(sources):
            work = staging / str(index)
            work.mkdir()
            spec = await prepare_module_source(
                source.source, work, modules_dir, source.ref
            )
            if spec.name in prepared:
                raise DependencyError(f"Duplicate module in package.yml: {spec.name}")
            prepared[spec.name] = spec
            destination = module_directory(modules_dir, spec.name)
            if destination.exists():
                if not destination.is_dir() or _source_tree(
                    destination
                ) != _source_tree(spec.directory):
                    raise DependencyError(
                        f"Module '{spec.name}' already exists with different content; existing sources are preserved"
                    )
            else:
                pending[spec.name] = (spec.directory, destination)

        ordered = ModuleCatalog(modules_dir).select(list(prepared), prepared=prepared)
        published = []
        publishing = True
        try:
            for name in ordered:
                if name not in pending:
                    continue
                root, destination = pending[name]
                root.rename(destination)
                published.append((root, destination))
            publishing = False
            yield
        except BaseException as failure:
            # A solved installation can be repaired by sync. An unsatisfiable
            # new source set must be withdrawn, or every later sync also fails.
            if not publishing and not isinstance(failure, DependencyResolutionError):
                raise
            errors = []
            for root, destination in reversed(published):
                try:
                    destination.rename(root)
                except OSError as exc:
                    errors.append(exc)
            if errors:
                raise BaseExceptionGroup(
                    "Package source rollback was incomplete; rerun install -r package.yml, then sync",
                    [failure, *errors],
                ) from None
            raise
